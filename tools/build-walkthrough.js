// Builds src/data/walkthrough.json from tools/walkthrough.src (see the
// header of that file for the line format).
//
//   node tools/build-walkthrough.js

'use strict';
const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, 'walkthrough.src');
const OUT = path.join(__dirname, '..', 'src', 'data', 'walkthrough.json');
const MAP = path.join(__dirname, '..', 'src', 'data', 'map.json');

const rooms = JSON.parse(fs.readFileSync(MAP, 'utf8')).rooms;

function parseDone(spec, lineNo) {
    const done = {};
    spec.split('||').map((s) => s.trim()).filter(Boolean).forEach((alt) => {
        if (alt === 'cmd') {
            done.cmd = true;
            return;
        }
        const eq = alt.indexOf('=');
        if (eq === -1) {
            throw new Error('line ' + lineNo + ': bad done "' + alt + '"');
        }
        const key = alt.slice(0, eq);
        const value = alt.slice(eq + 1).trim();
        if (key === 'text') {
            (done.text = done.text || []).push(value);
        } else if (key === 'arrive' || key === 'item' || key === 'placed') {
            if (done[key]) {
                throw new Error('line ' + lineNo + ': two "' + key + '" alternatives');
            }
            done[key] = value;
        } else {
            throw new Error('line ' + lineNo + ': unknown done kind "' + key + '"');
        }
    });
    return done;
}

const steps = [];
fs.readFileSync(SRC, 'utf8').split(/\r?\n/).forEach((raw, i) => {
    const line = raw.trim();
    if (!line || line.startsWith('#')) {
        return;
    }
    // Fields are separated by " | " -- plain "|" can't be used because the
    // "done" field uses " || " between alternatives.
    const fields = line.split(' | ');
    const at = fields[0].trim();
    const cmd = fields[1].trim();
    const why = fields[2].trim();
    const rest = fields.slice(3);
    // opts (gate / until= / fight=) is the final field iff it doesn't look
    // like a done spec.
    let doneSpec = rest.join(' | ');
    let opts = '';
    const lastIdx = rest.length - 1;
    if (rest.length > 1 && /^(gate|until=|fight=)/.test(rest[lastIdx].trim())) {
        opts = rest[lastIdx].trim();
        doneSpec = rest.slice(0, lastIdx).join(' | ');
    }
    if (!rooms[at]) {
        throw new Error('line ' + (i + 1) + ': unknown room "' + at + '"');
    }
    const step = { id: 's' + String(steps.length + 1).padStart(3, '0'), at: at, cmd: cmd, why: why, done: parseDone(doneSpec, i + 1) };
    if (step.done.arrive && !rooms[step.done.arrive]) {
        throw new Error('line ' + (i + 1) + ': unknown arrive room "' + step.done.arrive + '"');
    }
    const verify = {};
    opts.split(/\s+(?=gate|until=|fight=)/).filter(Boolean).forEach((o) => {
        if (o === 'gate') {
            step.gate = true;
        } else if (o.startsWith('until=')) {
            verify.until = o.slice(6).trim();
        } else if (o.startsWith('fight=')) {
            verify.until = o.slice(6).trim();
            verify.fight = true;
        }
    });
    if (verify.until) {
        step.verify = verify;
    }
    steps.push(step);
});

// Each step also records the game's score at the moment it becomes next, so
// the page's "Resync" button can find where a player who went off on their
// own has got to (room + score). Measured by replaying the route headlessly
// on the first seed where it plays clean (the thief and combat are random).
const { run } = require('./verify-walkthrough');
let scored = false;
for (let seed = 1; seed <= 400 && !scored; seed++) {
    const r = run(seed, false, steps);
    if (r.problems.length === 0 && r.won) {
        steps.forEach((step, i) => { step.score = r.scoreBefore[i]; });
        scored = true;
        console.log('step scores measured on seed ' + seed);
    }
}
if (!scored) {
    throw new Error('no seed in 1-400 plays the route cleanly -- run tools/verify-walkthrough.js --seed N to see what is wrong');
}

const comment = 'Generated by tools/build-walkthrough.js from tools/walkthrough.src -- edit that, not this. Each step: at = room id the command is typed in, why = spoiler-light hint, done = ANY of {arrive: room id, item: item id, placed: item id in trophy case, text: [phrases in new output], cmd: typed exactly}. gate = reaching this step also completes every earlier one. score = the game score when the step becomes next (measured by a headless replay). verify = hints for tools/verify-walkthrough.js only.';
// One step per line keeps the file diffable without being huge.
const body = steps.map((step) => '  ' + JSON.stringify(step)).join(',\n');
fs.writeFileSync(OUT, '{\n "_comment": ' + JSON.stringify(comment) + ',\n "steps": [\n' + body + '\n ]\n}\n');
console.log('wrote ' + steps.length + ' steps to ' + path.relative(process.cwd(), OUT));
